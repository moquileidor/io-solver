def extraer_nlp(pregunta: str) -> Optional[dict]:
    """Extrae función objetivo, variables y restricciones simbólicas como expresiones Python."""
    llm = ChatGroq(
        model=MODEL_REASONING,
        temperature=0.0,
        api_key=GROQ_API_KEY,
        reasoning_effort="medium",  # razonamiento medio para sustituir álgebra
        max_tokens=2048,
    )
    prompt = f"""Extrae el problema de optimización no lineal. Devuelve SOLO JSON con expresiones Python válidas:

{{
  "variables": ["x", "y"],
  "objetivo": "minimizar" | "maximizar",
  "funcion_objetivo": "150*x + 100000/x",
  "restricciones_eq": ["x*y - 1000"],
  "restricciones_ineq": [],
  "x0": [10, 100],
  "bounds": [[0.01, null], [0.01, null]]
}}

REGLAS DE EXPRESIONES:
- funcion_objetivo: expresión Python como string usando los nombres de variables.
- Operadores válidos: + - * / ** ( )
- Funciones disponibles: sqrt, log, exp, sin, cos, tan, pi, e (de la librería math)
- restricciones_eq: cada string es la EXPR del lado izquierdo, asumiendo "= 0".
  Ejemplo: "x*y - 1000" significa x*y = 1000.
- restricciones_ineq: cada string es EXPR >= 0.
  Ejemplo para x+y <= 10: pasa "10 - x - y" (que es >= 0).
- x0: punto inicial razonable (positivo si las variables son físicas, dentro de bounds).
- bounds: [[lo, hi], ...] mismo orden que variables. Usa null para infinito.

OPTIMIZACIÓN: Si una variable se puede despejar con una restricción de igualdad,
SIEMPRE sustitúyela y elimínala del problema. Esto reduce dimensiones y evita
problemas numéricos en el solver.

EJEMPLO 1: "minimizar 150x + 100y, sujeto a xy = 1000"
→ despeja y = 1000/x y sustituye:
{{"variables": ["x"], "objetivo": "minimizar",
  "funcion_objetivo": "150*x + 100*(1000/x)",
  "restricciones_eq": [], "restricciones_ineq": [],
  "x0": [10], "bounds": [[0.01, null]]}}

EJEMPLO 2: "P = 100 - 0.01Q, C = 50Q + 10000, maximizar Z = P*Q - C"
→ P está definido como función de Q, así que sustituye P en Z:
   Z = (100 - 0.01Q)*Q - (50Q + 10000)
   Z = 100Q - 0.01Q² - 50Q - 10000
   Z = -0.01Q² + 50Q - 10000
{{"variables": ["Q"], "objetivo": "maximizar",
  "funcion_objetivo": "-0.01*Q**2 + 50*Q - 10000",
  "restricciones_eq": [], "restricciones_ineq": [],
  "x0": [1000], "bounds": [[0.01, null]]}}

⚠️ REGLA CRÍTICA: Si el enunciado dice "P = f(Q)" o "y = g(x)", NUNCA trates
esa variable como independiente. Siempre sustituye y deja solo la variable base.
Esto aplica también a fórmulas de demanda, precio, costo unitario, etc.

Si no es NLP: {{"es_nlp": false}}

PROBLEMA:
{pregunta}
"""
    try:
        raw = con_retry(_invoke, llm, prompt, etiqueta="parse-nlp")
        raw = re.sub(r"```json|```", "", raw).strip()
        d = json.loads(raw)
        if d.get("es_nlp") is False:
            return None
        return d
    except Exception as e:
        print(f"⚠️  Parser NLP falló: {e}")
        return None


def validar_expresion_nlp(expr: str, variables: list) -> tuple[bool, str]:
    """
    Verifica que una expresión Python solo use las variables declaradas
    y funciones matemáticas conocidas. Retorna (es_valida, mensaje_error).
    """
    funciones_permitidas = {
        'sqrt', 'log', 'exp', 'sin', 'cos', 'tan',
        'pi', 'e', 'ln', 'abs', 'arcsin', 'arccos', 'arctan'
    }
    permitidas = set(variables) | funciones_permitidas

    # Extraer todos los identificadores (palabras alfabéticas) de la expresión
    identificadores = set(re.findall(r'\b[a-zA-Z_][a-zA-Z0-9_]*\b', expr))

    # Buscar identificadores que NO sean variables ni funciones permitidas
    no_definidos = identificadores - permitidas

    if no_definidos:
        return False, (
            f"La expresión '{expr}' usa variables no definidas: {no_definidos}. "
            f"Variables declaradas: {variables}. "
            f"Probablemente el extractor olvidó sustituir fórmulas (P, C, etc.)."
        )
    return True, ""

def resolver_nlp(data: dict) -> str:
    """scipy.optimize.minimize con SLSQP."""
    variables = data["variables"]
    n = len(variables)
    es_max = data.get("objetivo", "minimizar").lower().startswith("max")

    # 🔍 DEBUG: mostrar el JSON extraído para diagnosticar problemas de formulación
    print(f"   📋 JSON extraído por el LLM:")
    print(f"      Variables       : {data.get('variables')}")
    print(f"      Función objetivo: {data.get('funcion_objetivo')}")
    print(f"      Restricciones eq: {data.get('restricciones_eq')}")
    print(f"      Restricciones ineq: {data.get('restricciones_ineq')}")
    print(f"      Punto inicial   : {data.get('x0')}")
    print(f"      Bounds          : {data.get('bounds')}")


    # 🔍 VALIDAR que las expresiones solo usen variables declaradas
    fo = data.get("funcion_objetivo", "")
    valida, error = validar_expresion_nlp(fo, variables)
    if not valida:
        return (f"❌ Formulación NLP inválida: {error}\n\n"
                f"👉 El extractor no expandió correctamente las fórmulas. "
                f"La explicación del LLM abajo (que usa derivadas) es la correcta.")

    for expr in (data.get("restricciones_eq") or []) + (data.get("restricciones_ineq") or []):
        valida, error = validar_expresion_nlp(expr, variables)
        if not valida:
            return f"❌ Restricción inválida: {error}"

    # Contexto seguro para eval: solo math y las variables
    def make_eval_func(expr: str, sign: float = 1.0):
        # Compilar una vez para acelerar
        codigo = compile(expr, "<nlp_expr>", "eval")
        def f(x):
            ctx = {v: float(x[i]) for i, v in enumerate(variables)}
            ctx.update({
                "sqrt": math.sqrt, "log": math.log, "exp": math.exp,
                "sin": math.sin, "cos": math.cos, "tan": math.tan,
                "pi": math.pi, "e": math.e, "ln": math.log,
                "abs": abs,
            })
            return sign * eval(codigo, {"__builtins__": {}}, ctx)
        return f

    try:
        obj_func = make_eval_func(data["funcion_objetivo"], sign=-1.0 if es_max else 1.0)
    except Exception as e:
        return f"❌ No pude compilar la función objetivo: {e}"

    constraints = []
    try:
        for expr in data.get("restricciones_eq") or []:
            constraints.append({"type": "eq", "fun": make_eval_func(expr)})
        for expr in data.get("restricciones_ineq") or []:
            constraints.append({"type": "ineq", "fun": make_eval_func(expr)})
    except Exception as e:
        return f"❌ Error compilando restricciones: {e}"

    bounds = data.get("bounds") or [(None, None)] * n
    bounds = [tuple(b) if b else (None, None) for b in bounds]
    x0 = data.get("x0") or [1.0] * n

    try:
        r = minimize(
            obj_func, x0, method="SLSQP",
            bounds=bounds, constraints=constraints,
            options={"ftol": 1e-12, "maxiter": 500},
        )
    except Exception as e:
        return f"❌ scipy.optimize falló: {e}"

    if not r.success:
        # Intentar con un punto inicial diferente
        try:
            x0_alt = [v * 2 + 1 for v in x0]
            r = minimize(obj_func, x0_alt, method="SLSQP",
                         bounds=bounds, constraints=constraints,
                         options={"ftol": 1e-9, "maxiter": 1000})
        except Exception:
            pass

    if not r.success:
        return f"❌ NLP no convergió: {r.message}"

    valor = -r.fun if es_max else r.fun

    out = ["=== SOLUCIÓN EXACTA (NLP, scipy.optimize SLSQP) ==="]
    out.append(f"Estado : {r.message}")
    out.append(f"Iteraciones: {r.nit}")
    out.append(f"Valor {'máximo' if es_max else 'mínimo'} de la función objetivo = {valor:.6f}\n")
    out.append("Variables óptimas:")
    for nombre, val in zip(variables, r.x):
        out.append(f"  {nombre} = {val:.6f}")

    # Verificar restricciones
    if constraints:
        out.append("\nVerificación de restricciones:")
        for i, expr in enumerate(data.get("restricciones_eq") or []):
            f = make_eval_func(expr)
            val_eq = f(r.x)
            out.append(f"  EQ '{expr} = 0' → evaluado = {val_eq:.6e}")
        for i, expr in enumerate(data.get("restricciones_ineq") or []):
            f = make_eval_func(expr)
            val_ineq = f(r.x)
            tag = " ✓" if val_ineq >= -1e-6 else " ✗"
            out.append(f"  INEQ '{expr} >= 0' → evaluado = {val_ineq:.6e}{tag}")

    # 🚨 SANITY CHECK: detectar resultados absurdos
    if abs(valor) > 1e9:
        out.append(f"\n⚠️⚠️⚠️ ADVERTENCIA CRÍTICA ⚠️⚠️⚠️")
        out.append(f"El solver convergió a un valor absurdamente grande: {valor:.2e}")
        out.append(f"Esto casi siempre indica que el problema fue MAL FORMULADO por el extractor.")
        out.append(f"Posibles causas:")
        out.append(f"  - Variables que debieron sustituirse pero quedaron separadas")
        out.append(f"    (ej: P y Q como independientes cuando P = f(Q))")
        out.append(f"  - Restricciones no lineales mal expresadas")
        out.append(f"  - Punto inicial (x0) muy lejos del óptimo")
        out.append(f"\n👉 RECOMENDACIÓN: Ignora estos números. La explicación del LLM")
        out.append(f"   abajo (que usa derivadas) es probablemente la respuesta correcta.")

    # 🚨 SANITY CHECK 2: variable principal cerca de 0 cuando debería ser positiva
    for nombre, val in zip(variables, r.x):
        if 0 < val < 0.1 and abs(valor) > 1e6:
            out.append(f"\n⚠️  La variable {nombre}={val:.4f} es sospechosamente pequeña.")
            out.append(f"   Combinado con un valor objetivo enorme, sugiere mala formulación.")
            break

    return "\n".join(out)


