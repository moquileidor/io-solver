def respuesta_en_cache(pregunta: str) -> tuple[bool, Optional[str]]:
    """
    Solo evita re-resolver la MISMA pregunta consecutiva (sim >= 0.99).
    Útil cuando el usuario pega exactamente el mismo enunciado dos veces.
    NO se usa para responder problemas similares — esos se resuelven de cero.
    """
    res = supabase.table(TABLA_EJERC).select("pregunta, respuesta, embedding").order("id", desc=True).limit(200).execute()
    if not res.data:
        return False, None
    q_vec = encode(pregunta)
    mejor_sim = -1.0
    mejor_resp = None
    for row in res.data:
        try:
            vec = parse_embedding(row["embedding"])
            sim = cosine(q_vec, vec)
            if sim > mejor_sim:
                mejor_sim = sim
                mejor_resp = row["respuesta"]
        except Exception:
            continue
    if mejor_sim >= UMBRAL_CACHE:
        return True, mejor_resp
    return False, None


