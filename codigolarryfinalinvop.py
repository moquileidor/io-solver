def extraer_lp_json(pregunta: str) -> Optional[dict]:
    """Intenta extraer estructura LP. Devuelve dict o None."""
    llm = llm_fast(temperature=0.0)
    prompt = f"""Analiza el siguiente enunciado de Programación Lineal/Entera y devuelve ÚNICAMENTE un JSON válido sin texto adicional.

Formato exacto:
{{
  "es_lp": true,
  "objetivo": "maximizar" | "minimizar",
  "variables": ["x1", "x2", ...],
  "coeficientes_c": [c1, c2, ...],
  "A_ub": [[a11, a12, ...], ...] | null,
  "b_ub": [b1, ...] | null,
  "A_geq": [[a11, a12, ...], ...] | null,   // restricciones >=
  "b_geq": [b1, ...] | null,
  "A_eq": [[a11, a12, ...], ...] | null,
  "b_eq": [b1, ...] | null,
  "bounds": [[0, null], ...],
  "nombres_restricciones": ["nombre1", ...],
  "enteras": false  // true si las variables deben ser enteras
}}

REGLAS CRÍTICAS:
- TODAS las filas de A_ub, A_geq, A_eq deben tener EXACTAMENTE el mismo número de elementos que coeficientes_c.
- El número de filas en A_ub debe igualar la longitud de b_ub. Igual para A_geq/b_geq y A_eq/b_eq.
- bounds debe tener tantos elementos como coeficientes_c.
- Si el problema tiene productos de variables (xy, x*y), cocientes (1/x, a/x), potencias (x²),
  raíces, áreas/volúmenes implícitos o funciones no lineales: NO ES LP. Devuelve {{"es_lp": false}}.
- Si la única restricción es de tipo xy = constante: NO ES LP.

Si NO es LP/IP responde: {{"es_lp": false}}

ENUNCIADO:
{pregunta}
"""
    try:
        raw = con_retry(_invoke, llm, prompt, etiqueta="parse-LP")
        raw = re.sub(r"```json|```", "", raw).strip()
        d = json.loads(raw)
        if not d.get("es_lp"):
            return None
        if not validar_estructura_lp(d):
            print("⚠️  Extractor LP devolvió estructura inconsistente — descartado")
            return None
        return d
    except Exception as e:
        print(f"⚠️  Parser LP falló: {e}")
        return None


def validar_estructura_lp(lp: dict) -> bool:
    """Valida que las dimensiones del JSON sean consistentes con scipy.linprog."""
    c = lp.get("coeficientes_c")
    if not c or not isinstance(c, list) or len(c) == 0:
        return False
    n = len(c)

    for clave_A, clave_b in [("A_ub", "b_ub"), ("A_geq", "b_geq"), ("A_eq", "b_eq")]:
        A = lp.get(clave_A)
        b = lp.get(clave_b)
        if A is None and b is None:
            continue
        if A is None or b is None:
            return False
        if not isinstance(A, list) or not isinstance(b, list):
            return False
        if len(A) != len(b):
            return False
        for fila in A:
            if not isinstance(fila, list) or len(fila) != n:
                return False

    bounds = lp.get("bounds")
    if bounds is not None and len(bounds) != n:
        return False

    # Debe tener al menos UNA restricción
    if not any(lp.get(k) for k in ("A_ub", "A_geq", "A_eq")):
        return False

    return True


def resolver_lp_continuo(lp: dict) -> str:
    """Resuelve con scipy.linprog. Genera reporte tipo human-readable."""
    c = lp["coeficientes_c"]
    n = len(c)
    es_max = lp.get("objetivo", "maximizar").lower().startswith("max")
    c_scipy = [-v for v in c] if es_max else c

    # Combinar A_ub con A_geq (geq se convierte multiplicando por -1)
    A_ub = list(lp.get("A_ub") or [])
    b_ub = list(lp.get("b_ub") or [])
    if lp.get("A_geq"):
        for fila, rhs in zip(lp["A_geq"], lp["b_geq"]):
            A_ub.append([-x for x in fila])
            b_ub.append(-rhs)

    A_ub_np = np.array(A_ub) if A_ub else None
    b_ub_np = np.array(b_ub) if b_ub else None
    A_eq_np = np.array(lp["A_eq"]) if lp.get("A_eq") else None
    b_eq_np = np.array(lp["b_eq"]) if lp.get("b_eq") else None

    bounds = lp.get("bounds") or [(0, None)] * n
    bounds_scipy = [(b[0], b[1]) for b in bounds]

    try:
        r = linprog(
            c=c_scipy, A_ub=A_ub_np, b_ub=b_ub_np,
            A_eq=A_eq_np, b_eq=b_eq_np,
            bounds=bounds_scipy, method='highs',
        )
    except Exception as e:
        return f"❌ scipy.linprog error: {e}"

    if not r.success:
        return f"❌ No óptimo: {r.message}"

    z = -r.fun if es_max else r.fun
    vars_nombres = lp.get("variables", [f"x{i+1}" for i in range(n)])
    nombres_r = lp.get("nombres_restricciones", [])

    out = ["=== SOLUCIÓN EXACTA (scipy HiGHS) ==="]
    out.append(f"Estado : {r.message}")
    out.append(f"Z {'máximo' if es_max else 'mínimo'} = {z:.6f}\n")
    out.append("Variables óptimas:")
    for nombre, val in zip(vars_nombres, r.x):
        out.append(f"  {nombre} = {val:.6f}")

    # Holguras
    if A_ub_np is not None and b_ub_np is not None and len(A_ub_np) > 0:
        out.append("\nHolguras (b - A·x):")
        for idx, (fila, rhs) in enumerate(zip(A_ub_np, b_ub_np)):
            uso = float(np.dot(fila, r.x))
            holg = float(rhs) - uso
            nombre = nombres_r[idx] if idx < len(nombres_r) else f"R{idx+1}"
            tag = " ← ACTIVA" if abs(holg) < 1e-6 else ""
            out.append(f"  {nombre}: usado={uso:.4f}, dispon={float(rhs)}, holgura={holg:.4f}{tag}")

    # Verificación
    valida, errores = verificar_solucion_lp(lp, r.x.tolist())
    if valida:
        out.append("\n✅ Verificación: solución cumple TODAS las restricciones")
    else:
        out.append(f"\n⚠️  Verificación falló: {errores}")

    return "\n".join(out)


def resolver_lp_entero(lp: dict) -> str:
    """IP con PuLP/CBC."""
    c = lp["coeficientes_c"]
    n = len(c)
    es_max = lp.get("objetivo", "maximizar").lower().startswith("max")
    sentido = pulp.LpMaximize if es_max else pulp.LpMinimize
    prob = pulp.LpProblem("IP", sentido)

    vars_nombres = lp.get("variables", [f"x{i+1}" for i in range(n)])
    bounds = lp.get("bounds") or [(0, None)] * n
    cat = 'Integer'
    x = [
        pulp.LpVariable(vars_nombres[i], lowBound=bounds[i][0], upBound=bounds[i][1], cat=cat)
        for i in range(n)
    ]

    prob += pulp.lpSum(c[i] * x[i] for i in range(n))

    for fila, rhs in zip(lp.get("A_ub") or [], lp.get("b_ub") or []):
        prob += pulp.lpSum(fila[i] * x[i] for i in range(n)) <= rhs
    for fila, rhs in zip(lp.get("A_geq") or [], lp.get("b_geq") or []):
        prob += pulp.lpSum(fila[i] * x[i] for i in range(n)) >= rhs
    for fila, rhs in zip(lp.get("A_eq") or [], lp.get("b_eq") or []):
        prob += pulp.lpSum(fila[i] * x[i] for i in range(n)) == rhs

    prob.solve(pulp.PULP_CBC_CMD(msg=False))
    estado = pulp.LpStatus[prob.status]
    if estado != 'Optimal':
        return f"❌ IP no óptimo: {estado}"

    z = pulp.value(prob.objective)
    out = ["=== SOLUCIÓN EXACTA (PuLP / CBC, enteros) ==="]
    out.append(f"Estado : {estado}")
    out.append(f"Z {'máximo' if es_max else 'mínimo'} = {z:.6f}\n")
    out.append("Variables óptimas:")
    for v in prob.variables():
        out.append(f"  {v.name} = {v.varValue}")
    return "\n".join(out)


def verificar_solucion_lp(lp: dict, x: list[float], tol: float = 1e-4) -> tuple[bool, str]:
    """Verifica que x cumple todas las restricciones del LP."""
    errores = []
    x_np = np.array(x)
    for fila, rhs in zip(lp.get("A_ub") or [], lp.get("b_ub") or []):
        if np.dot(fila, x_np) > rhs + tol:
            errores.append(f"R≤ violada: {np.dot(fila, x_np):.4f} > {rhs}")
    for fila, rhs in zip(lp.get("A_geq") or [], lp.get("b_geq") or []):
        if np.dot(fila, x_np) < rhs - tol:
            errores.append(f"R≥ violada: {np.dot(fila, x_np):.4f} < {rhs}")
    for fila, rhs in zip(lp.get("A_eq") or [], lp.get("b_eq") or []):
        if abs(np.dot(fila, x_np) - rhs) > tol:
            errores.append(f"R= violada: {np.dot(fila, x_np):.4f} ≠ {rhs}")
    bounds = lp.get("bounds") or [(0, None)] * len(x)
    for i, (lo, hi) in enumerate(bounds):
        if lo is not None and x[i] < lo - tol:
            errores.append(f"x{i+1}={x[i]:.4f} < lo={lo}")
        if hi is not None and x[i] > hi + tol:
            errores.append(f"x{i+1}={x[i]:.4f} > hi={hi}")
    return (len(errores) == 0), "; ".join(errores)


