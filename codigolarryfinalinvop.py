TIPOS_VALIDOS = [
    "LP", "IP", "TRANSPORTE", "ASIGNACION", "FLUJO_MAX",
    "RUTA_CORTA", "PERT_CPM", "COLAS_MM1", "COLAS_MMC", "EOQ", "NLP", "OTRO",
]


def clasificar_problema(pregunta: str) -> str:
    """
    Clasificador con 2 capas:
    1. Heurísticas por palabras clave (rápido, casos obvios)
    2. LLM con razonamiento (casos ambiguos)
    """
    pregunta_lower = pregunta.lower()

    # ============ CAPA 1: Heurísticas por palabras clave ============

    # M/M/c (>= 2 servidores): aparece "c servidores", "c=2", "varios servidores"
    if (re.search(r'\b(c\s*=\s*[2-9]|[2-9]\s*servidores|servidores en paralelo|múltiples servidores)\b', pregunta_lower)
        and re.search(r'(lambda|tasa de llegada)', pregunta_lower)):
        return "COLAS_MMC"

    # M/M/1: tiene lambda Y mu (con o sin "tasa")
    tiene_lambda = bool(re.search(r'(lambda|tasa de llegada|λ)', pregunta_lower))
    tiene_mu = bool(re.search(r'(\bmu\b|tasa de servicio|μ)', pregunta_lower))
    if tiene_lambda and tiene_mu:
        print("   🎯 Clasificado por heurística (lambda + mu detectados)")
        return "COLAS_MM1"

    # EOQ: palabras de inventario
    if re.search(r'(eoq|cantidad económica|punto de reorden|costo de pedido|costo de mantenimiento|demanda anual)', pregunta_lower):
        return "EOQ"

    # PERT/CPM
    if re.search(r'(pert|cpm|ruta crítica|actividades.*duración|predecesores|cronograma)', pregunta_lower):
        return "PERT_CPM"

    # Flujo máximo
    if re.search(r'(flujo máximo|maximum flow|ford.?fulkerson|capacidad de.*arco)', pregunta_lower):
        return "FLUJO_MAX"

    # Asignación
    if re.search(r'(asignar.*tareas|matriz.*asignación|húngaro|hungarian)', pregunta_lower):
        return "ASIGNACION"

    # ============ CAPA 2: LLM para casos ambiguos ============

    llm = ChatGroq(
        model=MODEL_REASONING,
        temperature=0.0,
        api_key=GROQ_API_KEY,
        reasoning_effort="medium",   # subido de "low"
        max_tokens=1024,             # subido de 512
    )
    prompt = f"""Clasifica el siguiente problema de Investigación de Operaciones en UNA sola categoría.

Categorías válidas:
- LP             : Programación lineal CONTINUA. La función objetivo y TODAS las restricciones
                   son SUMAS de términos a*x_i (constante por variable). Variables reales.
- IP             : Igual que LP pero variables ENTERAS o BINARIAS.
- TRANSPORTE     : Orígenes con oferta, destinos con demanda, matriz de costos de envío.
- ASIGNACION     : Asignar n agentes a n tareas (matriz cuadrada de costos).
- FLUJO_MAX      : Red dirigida con capacidades en arcos, fuente y sumidero.
- RUTA_CORTA     : Ruta más corta entre dos nodos en grafo con pesos.
- PERT_CPM       : Cronograma de proyecto con actividades, predecesores y duraciones.
- COLAS_MM1      : Cola con 1 servidor. Suele dar lambda (tasa de llegada) y mu (tasa de servicio).
                   Si menciona "tasa de llegada" + "tasa de servicio" → es M/M/1.
- COLAS_MMC      : Cola con c >= 2 servidores en paralelo.
- EOQ            : Cantidad económica de pedido / ROP / inventarios. Suele dar D, S, H, lead time.
- NLP            : Programación NO lineal. Usa esta categoría si aparece CUALQUIERA de:
                   * producto de variables (xy, x*y, x·y, P*Q donde P depende de Q)
                   * potencias (x², x^2, x³, x^n con n != 1)
                   * función de demanda P(Q) que multiplica por Q (genera Q² implícito)
                   * cocientes (1/x, a/x, x/y)
                   * raíces (sqrt(x), x^0.5)
                   * funciones (sin, cos, log, ln, exp)
                   * restricciones tipo xy = constante, x²+y² = r
                   * problemas con áreas (m²) o volúmenes (m³)
- OTRO           : No encaja en ninguna anterior.

REGLA DE ORO 1: si el enunciado contiene productos de variables, áreas, volúmenes,
divisiones, raíces, derivadas o funciones no lineales → ES NLP, NUNCA LP.

REGLA DE ORO 2: si la función objetivo es Beneficio = Ingresos - Costo donde
Ingresos = P*Q y P depende linealmente de Q (ej. P = 100 - 0.01Q), entonces el
producto P*Q genera Q² → ES NLP.

REGLA DE ORO 3: si solo hay lambda y mu sin más restricciones, es COLAS_MM1
(no OTRO).

REGLA DE ORO 4: si el enunciado menciona "enviar N unidades de X a Y" con costos
de transporte y NODOS INTERMEDIOS ("pasando por", "vía", "transbordo"),
ES TRANSPORTE (no RUTA_CORTA). RUTA_CORTA es para encontrar el camino más corto
en un grafo, sin restricción de cantidad de flujo.

Razona brevemente y responde con UNA sola palabra de la lista en la última línea.

PROBLEMA:
{pregunta}
"""
    try:
        raw = con_retry(_invoke, llm, prompt, etiqueta="clasif").strip().upper()
        for linea in reversed(raw.splitlines()):
            linea = linea.strip()
            palabras = re.findall(r'[A-Z_]+', linea)
            for p in palabras:
                if p in TIPOS_VALIDOS:
                    return p
        return "OTRO"
    except Exception as e:
        print(f"⚠️  Clasificador falló: {e}")
        return "OTRO"


