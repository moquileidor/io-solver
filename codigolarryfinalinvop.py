def resolver_pert(data: dict) -> str:
    """Calcula early/late times, holguras y ruta crítica."""
    acts = {a["nombre"]: a for a in data["actividades"]}
    nombres = list(acts.keys())

    # Forward pass: ES (Early Start), EF (Early Finish)
    ES, EF = {}, {}
    pendientes = set(nombres)
    while pendientes:
        progreso = False
        for n in list(pendientes):
            preds = acts[n]["predecesores"]
            if all(p in EF for p in preds):
                ES[n] = max([EF[p] for p in preds], default=0)
                EF[n] = ES[n] + acts[n]["duracion"]
                pendientes.remove(n)
                progreso = True
        if not progreso:
            return "❌ Ciclo o predecesores inválidos en el grafo"

    duracion_proyecto = max(EF.values())

    # Backward pass: LF (Late Finish), LS (Late Start)
    sucesores = {n: [] for n in nombres}
    for n in nombres:
        for p in acts[n]["predecesores"]:
            sucesores[p].append(n)

    LF, LS = {}, {}
    pendientes = set(nombres)
    while pendientes:
        progreso = False
        for n in list(pendientes):
            sucs = sucesores[n]
            if all(s in LS for s in sucs):
                LF[n] = min([LS[s] for s in sucs], default=duracion_proyecto)
                LS[n] = LF[n] - acts[n]["duracion"]
                pendientes.remove(n)
                progreso = True
        if not progreso:
            return "❌ Error en backward pass"

    # Holguras
    holguras = {n: LS[n] - ES[n] for n in nombres}
    criticas = [n for n, h in holguras.items() if abs(h) < 1e-9]

    out = ["=== SOLUCIÓN EXACTA (PERT/CPM) ==="]
    out.append(f"Duración del proyecto: {duracion_proyecto}\n")
    out.append(f"{'Act':<6} {'Dur':<5} {'ES':<5} {'EF':<5} {'LS':<5} {'LF':<5} {'Holg':<6} {'Crit'}")
    for n in nombres:
        crit = "✓" if n in criticas else ""
        out.append(f"{n:<6} {acts[n]['duracion']:<5} {ES[n]:<5} {EF[n]:<5} {LS[n]:<5} {LF[n]:<5} {holguras[n]:<6} {crit}")
    out.append(f"\nRuta crítica: {' → '.join(criticas)}")
    return "\n".join(out)


