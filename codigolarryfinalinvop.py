def encode(texto: str) -> np.ndarray:
    """Codifica un texto a vector. Single text → 1D array."""
    if isinstance(texto, str):
        return embedding_model.encode([texto])[0]
    return embedding_model.encode(texto)


def cosine(a: np.ndarray, b: np.ndarray) -> float:
    return float(np.dot(a, b) / (np.linalg.norm(a) * np.linalg.norm(b) + 1e-9))


def parse_embedding(raw) -> np.ndarray:
    """Supabase puede devolver embedding como string JSON o como lista."""
    if isinstance(raw, str):
        raw = json.loads(raw)
    return np.array(raw, dtype=np.float32)


