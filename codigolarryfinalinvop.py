def resolver_numericamente(pregunta: str, tipo: str) -> tuple[str, str]:
    """
    Devuelve (solucion_exacta, tipo_efectivo). Si no se pudo, ('', tipo).
    """
    try:
        if tipo in ("LP", "IP"):
            lp = extraer_lp_json(pregunta)
            if not lp or not lp.get("es_lp"):
                return "", tipo
            if tipo == "IP" or lp.get("enteras"):
                return resolver_lp_entero(lp), "IP"
            return resolver_lp_continuo(lp), "LP"

        if tipo == "TRANSPORTE":
            # Intentar modelo clásico de 2 capas
            data = extraer_transporte(pregunta)
            if data:
                return resolver_transporte(data), tipo

            # Fallback: modelo de red con nodos intermedios
            print("   ⚠️  Transporte clásico rechazado, probando modelo de red...")
            data_red = extraer_red_transporte(pregunta)
            if data_red:
                return resolver_red_transporte(data_red), tipo

        if tipo == "ASIGNACION":
            data = extraer_asignacion(pregunta)
            if data:
                return resolver_asignacion(data), tipo

        if tipo == "FLUJO_MAX":
            data = extraer_grafo_flujo(pregunta)
            if data:
                return resolver_flujo_max(data), tipo

        if tipo == "RUTA_CORTA":
            data = extraer_grafo_ruta(pregunta)
            if data:
                return resolver_ruta_corta(data), tipo

        if tipo == "PERT_CPM":
            data = extraer_pert(pregunta)
            if data:
                return resolver_pert(data), tipo

        if tipo in ("COLAS_MM1", "COLAS_MMC"):
            data = extraer_colas(pregunta)
            if data:
                return resolver_colas(data), tipo

        if tipo == "EOQ":
            data = extraer_eoq(pregunta)
            if data:
                return resolver_eoq(data), tipo

        if tipo == "NLP":
            data = extraer_nlp(pregunta)
            if data:
                return resolver_nlp(data), tipo
    except Exception as e:
        print(f"⚠️  Solver numérico falló para {tipo}: {e}")

    return "", tipo


