    cut_value, (S_set, T_set) = nx.minimum_cut(G, fuente, sumidero)
    out.append(f"\nCorte mínimo = {cut_value} (= flujo máximo, teorema max-flow min-cut)")
    out.append(f"Conjunto S: {sorted(S_set)}")
    out.append(f"Conjunto T: {sorted(T_set)}")
    return "\n".join(out)


