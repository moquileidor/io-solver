def extraer_colas(pregunta: str) -> Optional[dict]:
    """Extrae parámetros de cola. Primero intenta regex, luego LLM."""

    # ============ CAPA 1: Regex (rápido, 0 tokens) ============
    pregunta_norm = pregunta.lower().replace(',', '.')

    # Buscar lambda: "lambda = 3", "λ = 3", "tasa de llegada = 3", "λ=3"
    lambda_match = re.search(
        r'(?:lambda|λ|tasa de llegada)\s*[=:]?\s*(\d+(?:\.\d+)?)',
        pregunta_norm
    )

    # Buscar mu: "mu = 5", "μ = 5", "tasa de servicio = 5"
    mu_match = re.search(
        r'(?:\bmu\b|μ|tasa de servicio)\s*[=:]?\s*(\d+(?:\.\d+)?)',
        pregunta_norm
    )

    # Buscar c (servidores): "c = 2", "2 servidores", "c=3"
    c_match = re.search(
        r'(?:\bc\s*[=:]?\s*(\d+)|(\d+)\s*servidores?)',
        pregunta_norm
    )
    c = 1  # default M/M/1
    if c_match:
        c = int(c_match.group(1) or c_match.group(2))

    if lambda_match and mu_match:
        return {
            "tipo": "M/M/1" if c == 1 else f"M/M/{c}",
            "lambda": float(lambda_match.group(1)),
            "mu": float(mu_match.group(1)),
            "c": c,
        }

    # ============ CAPA 2: LLM como fallback ============
    llm = llm_fast(temperature=0.0)
    prompt = f"""Extrae los parámetros del sistema de colas. Devuelve SOLO JSON:

{{
  "tipo": "M/M/1" | "M/M/c",
  "lambda": 10,
  "mu": 12,
  "c": 1
}}

REGLAS:
- "lambda" = tasa de llegada (clientes por unidad de tiempo)
- "mu" = tasa de servicio (clientes por unidad de tiempo)
- "c" = número de servidores (default 1 para M/M/1)

EJEMPLOS:
- "λ=3 autos/h, μ=5 autos/h" → {{"tipo":"M/M/1","lambda":3,"mu":5,"c":1}}
- "tasa de llegada 10, tasa de servicio 12" → {{"tipo":"M/M/1","lambda":10,"mu":12,"c":1}}

Si no es problema de colas: {{"es_colas": false}}

PROBLEMA:
{pregunta}
"""
    try:
        raw = con_retry(_invoke, llm, prompt, etiqueta="parse-colas")
        raw = re.sub(r"```json|```", "", raw).strip()
        d = json.loads(raw)
        if d.get("es_colas") is False:
            return None
        return d
    except Exception as e:
        print(f"⚠️  Parser colas falló: {e}")
        return None


def resolver_colas(data: dict) -> str:

    # 🔍 DEBUG
    print(f"   📋 Parámetros extraídos:")
    print(f"      λ (lambda) = {data.get('lambda')}")
    print(f"      μ (mu)     = {data.get('mu')}")
    print(f"      c          = {data.get('c', 1)}")

    lam = float(data["lambda"])

    mu = float(data["mu"])
    c = int(data.get("c", 1))
    rho = lam / (c * mu)

    if rho >= 1:
        return f"❌ Sistema inestable (ρ = {rho:.4f} ≥ 1). Las colas crecen sin límite."

    out = ["=== SOLUCIÓN EXACTA (Teoría de Colas) ==="]
    out.append(f"λ = {lam}, μ = {mu}, c = {c}")

    if c == 1:
        L = lam / (mu - lam)
        Lq = (lam ** 2) / (mu * (mu - lam))
        W = 1 / (mu - lam)
        Wq = lam / (mu * (mu - lam))
        P0 = 1 - rho
        out.append(f"\n--- M/M/1 ---")
    else:
        # M/M/c
        suma = sum((lam/mu)**n / math.factorial(n) for n in range(c))
        suma += ((lam/mu)**c / math.factorial(c)) * (1 / (1 - rho))
        P0 = 1 / suma
        Lq = (P0 * (lam/mu)**c * rho) / (math.factorial(c) * (1 - rho)**2)
        L = Lq + lam/mu
        Wq = Lq / lam
        W = Wq + 1/mu
        out.append(f"\n--- M/M/{c} ---")

    out.append(f"ρ (utilización)         = {rho:.4f} ({rho*100:.2f}%)")
    out.append(f"P0 (sistema vacío)      = {P0:.4f}")
    out.append(f"L  (clientes en sistema)= {L:.4f}")
    out.append(f"Lq (clientes en cola)   = {Lq:.4f}")
    out.append(f"W  (tiempo en sistema)  = {W:.4f}")
    out.append(f"Wq (tiempo en cola)     = {Wq:.4f}")
    return "\n".join(out)


