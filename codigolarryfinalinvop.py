def resolver_asignacion(data: dict) -> str:
    """scipy.optimize.linear_sum_assignment (algoritmo Húngaro)."""
    agentes = data["agentes"]
    tareas = data["tareas"]
    matriz = np.array(data["costos"], dtype=float)
    es_max = data.get("objetivo", "minimizar").lower().startswith("max")

    if matriz.shape[0] != matriz.shape[1]:
        return f"❌ Matriz no cuadrada: {matriz.shape}. Balancea agregando filas/columnas ficticias."

    # Hungaro minimiza por defecto. Para max negamos.
    matriz_solver = -matriz if es_max else matriz
    fila_idx, col_idx = linear_sum_assignment(matriz_solver)

    out = ["=== SOLUCIÓN EXACTA (Algoritmo Húngaro, scipy) ==="]
    sentido = "máximo" if es_max else "mínimo"
    valor_total = float(matriz[fila_idx, col_idx].sum())
    out.append(f"Valor {sentido} total: {valor_total:.4f}\n")
    out.append("Asignación óptima:")
    for i, j in zip(fila_idx, col_idx):
        out.append(f"  {agentes[i]} ↔ {tareas[j]}: costo = {matriz[i][j]:.2f}")
    return "\n".join(out)


