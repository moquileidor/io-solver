def resolver_red_transporte(data: dict) -> str:
    """Red de transporte con nodos intermedios. LP con balance de flujo."""
    nodos = data["nodos"]
    arcos = data["arcos"]
    nombres = [n["nombre"] for n in nodos]
    balance = {n["nombre"]: float(n["balance"]) for n in nodos}

    if abs(sum(balance.values())) > 1e-6:
        return (f"❌ Red desbalanceada: Σ balance = {sum(balance.values()):.4f} ≠ 0. "
                f"Agrega un nodo ficticio.")

    n_vars = len(arcos)
    c = [float(a["costo"]) for a in arcos]

    # Una restricción de balance por cada nodo
    A_eq, b_eq = [], []
    for k in nombres:
        fila = [0.0] * n_vars
        for idx, a in enumerate(arcos):
            if a["de"] == k:
                fila[idx] += 1.0   # sale
            if a["a"] == k:
                fila[idx] -= 1.0   # entra
        A_eq.append(fila)
        b_eq.append(balance[k])

    bounds = []
    for a in arcos:
        cap = a.get("capacidad")
        bounds.append((0, cap if cap is not None else None))

    r = linprog(c=c, A_eq=A_eq, b_eq=b_eq, bounds=bounds, method='highs')
    if not r.success:
        return f"❌ scipy.linprog no resolvió red de transporte: {r.message}"

    out = ["=== SOLUCIÓN EXACTA (Red de Transporte con intermedios, scipy HiGHS) ==="]
    out.append(f"Costo total mínimo: {r.fun:.4f}\n")
    out.append("Flujo óptimo por arco (no cero):")
    for idx, a in enumerate(arcos):
        x = r.x[idx]
        if x > 1e-6:
            out.append(f"  {a['de']} → {a['a']}: {x:.2f} u × ${a['costo']} = ${x * a['costo']:.2f}")

    # Verificación de balance
    out.append("\nVerificación de balance por nodo:")
    for k in nombres:
        sale = sum(r.x[i] for i, a in enumerate(arcos) if a["de"] == k)
        entra = sum(r.x[i] for i, a in enumerate(arcos) if a["a"] == k)
        neto = sale - entra
        out.append(f"  {k}: sale={sale:.2f}, entra={entra:.2f}, neto={neto:+.2f} (esperado {balance[k]:+.2f})")

    return "\n".join(out)


