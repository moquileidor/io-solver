def extraer_segundos(error, default=60):
    m = re.search(r'retry in (\d+(?:\.\d+)?)\s*s', str(error), re.IGNORECASE)
    return int(float(m.group(1))) + 2 if m else default


def con_retry(fn, *args, max_intentos=6, etiqueta="op", **kwargs):
    for intento in range(1, max_intentos + 1):
        try:
            return fn(*args, **kwargs)
        except Exception as e:
            es_quota = any(x in str(e) for x in ["429", "RESOURCE_EXHAUSTED", "rate_limit"])
            if es_quota and intento < max_intentos:
                espera = extraer_segundos(e)
                print(f"⏳ [{etiqueta}] Rate limit — {intento}/{max_intentos}, esperando {espera}s")
                time.sleep(espera)
            else:
                raise
    raise RuntimeError(f"[{etiqueta}] Reintentos agotados.")


