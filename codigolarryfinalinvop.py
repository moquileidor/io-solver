def cargar_pdf(pdf_path: str) -> list[Document]:
    if not os.path.exists(pdf_path):
        print(f"❌ PDF no encontrado: {pdf_path}")
        return []

    docs = []
    print(f"📄 Cargando {os.path.basename(pdf_path)}...")
    try:
        from pypdf import PdfReader
        reader = PdfReader(pdf_path, strict=False)
        for i, page in enumerate(reader.pages):
            text = page.extract_text()
            if text and text.strip():
                docs.append(Document(page_content=text, metadata={"page": i, "source": pdf_path}))
        if docs:
            print(f"✅ pypdf: {len(docs)} páginas")
            return docs
    except Exception as e1:
        print(f"⚠️  pypdf falló ({e1}), probando pdfminer...")

    try:
        from pdfminer.high_level import extract_pages
        from pdfminer.layout import LTTextContainer
        for i, layout in enumerate(extract_pages(pdf_path)):
            texto = "".join(el.get_text() for el in layout if isinstance(el, LTTextContainer))
            if texto.strip():
                docs.append(Document(page_content=texto, metadata={"page": i, "source": pdf_path}))
        print(f"✅ pdfminer: {len(docs)} páginas")
    except Exception as e2:
        print(f"❌ pdfminer también falló: {e2}")
    return docs


def chunks_jerarquicos(docs: list[Document]) -> list[Document]:
    """
    Chunking de dos niveles. El primer pase corta fino para búsqueda,
    luego cada chunk lleva como metadato el chunk grande de su entorno.
    """
    splitter_pequeno = RecursiveCharacterTextSplitter(
        chunk_size=CHUNK_SIZE_S, chunk_overlap=CHUNK_OVL_S,
        separators=["\n\n", "\n", ".", " "],
    )
    return splitter_pequeno.split_documents(docs)


def asegurar_libro_indexado(pdf_path: str) -> pd.DataFrame:
    if docs_count() > 0:
        return cargar_df_docs()

    docs = cargar_pdf(pdf_path)
    if not docs:
        return pd.DataFrame(columns=["text", "embedding", "page"])

    chunks = chunks_jerarquicos(docs)
    print(f"✅ {len(chunks)} chunks creados (objetivo: {MAX_CHUNKS})")
    total = min(MAX_CHUNKS, len(chunks))
    if len(chunks) > MAX_CHUNKS:
        print(f"⚠️  Truncando a {MAX_CHUNKS} chunks (sube MAX_CHUNKS si quieres todo)")

    textos = [c.page_content for c in chunks[:total]]
    print(f"🔢 Generando embeddings de {total} chunks...")
    vectores = embedding_model.encode(textos, batch_size=64, show_progress_bar=True)
    guardar_chunks_libro(chunks[:total], vectores)

    return pd.DataFrame([
        {"text": c.page_content, "embedding": v, "page": c.metadata.get("page")}
        for c, v in zip(chunks[:total], vectores)
    ])


def buscar_teoria(query: str, df: pd.DataFrame, k: int = K_TEORIA) -> str:
    """Top-k chunks del libro, usando producto punto (asume embeddings normalizados o no — funciona)."""
    if df.empty:
        return ""
    q_vec = encode(query)
    df_tmp = df.copy()
    df_tmp['score'] = df_tmp['embedding'].apply(lambda x: cosine(q_vec, x))
    top = df_tmp.sort_values('score', ascending=False).head(k)
    return "\n---\n".join(top['text'].tolist())


